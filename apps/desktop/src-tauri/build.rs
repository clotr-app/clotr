fn main() {
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_ONE_CLOTR");
    println!("cargo:rerun-if-env-changed=CARGO_FEATURE_SCAN_TIMES");
    for watched in [
        "../tools/prepare-ui.js",
        "src/feature_gates.rs",
        "Cargo.toml",
        "../../locales",
        "../../engine",
        "../../ai-apps.json",
        "../../terminal-apps.json",
        "../../../extension",
        "../../../tools/engine-bundle.js",
        "../../../design/suite",
    ] {
        println!("cargo:rerun-if-changed={watched}");
    }
    // Tauri leaves permission files for commands that disappeared. Rebuild them from the current feature set so a
    // One Clotr grant from an earlier build cannot make the default Store build carry it.
    let generated_permissions = std::path::PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR").expect("Cargo sets CARGO_MANIFEST_DIR"),
    )
    .join("permissions")
    .join("autogenerated");
    match std::fs::remove_dir_all(&generated_permissions) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => panic!(
            "couldn't clear stale Tauri permissions at {}: {error}",
            generated_permissions.display()
        ),
    }
    // The terminal list lives beside clotr.exe, never inside it (the Store's certification kit flags terminal names
    // found in a program). msix.ps1 puts it in the package; this puts it beside every local build, so a build run
    // straight from target\ (the Newest work launcher's) finds it too. OUT_DIR is target\<profile>\build\<crate>\out.
    let features = feature_gates::DesktopFeatures::new(
        std::env::var_os("CARGO_FEATURE_ONE_CLOTR").is_some(),
        std::env::var_os("CARGO_FEATURE_SCAN_TIMES").is_some(),
    );
    if let Some(profile_dir) = std::env::var_os("OUT_DIR")
        .map(std::path::PathBuf::from)
        .and_then(|out| out.ancestors().nth(3).map(std::path::Path::to_path_buf))
    {
        let _ = std::fs::copy("../../terminal-apps.json", profile_dir.join("terminal-apps.json"));
        let feature_record = profile_dir.join("desktop-build-features.json");
        std::fs::write(
            &feature_record,
            format!(
                "{{\"oneClotr\":{},\"scanTimes\":{}}}\n",
                features.one_clotr_enabled(),
                features.scan_times_enabled()
            ),
        )
        .expect("write the feature record next to the built app");
        println!("cargo:rustc-env=CLOTR_BUILD_FEATURES_PATH={}", feature_record.display());
    }
    let prepared = Command::new("node")
        .arg("../tools/prepare-ui.js")
        .env("CLOTR_ONE_CLOTR_ENABLED", features.one_clotr_enabled().to_string())
        .env("CLOTR_SCAN_TIMES_ENABLED", features.scan_times_enabled().to_string())
        .status();
    match prepared {
        Ok(s) if s.success() => {}
        _ => panic!("Clotr's pages need Node to prepare (node tools/prepare-ui.js in apps/desktop)"),
    }
    let mut commands = COMMANDS.to_vec();
    commands.extend_from_slice(features.one_clotr_commands());
    let command_names: &'static [&'static str] = Box::leak(commands.into_boxed_slice());
    let manifest = tauri_build::AppManifest::new().commands(command_names);
    // Per-monitor v2 DPI awareness, declared the way Microsoft's own high-DPI guide does it
    // (https://learn.microsoft.com/windows/win32/hidpi/setting-the-default-dpi-awareness-for-a-process): tauri-build's
    // own default Windows manifest (windows-app-manifest.xml in its own crate) carries the Common Controls v6
    // dependency tauri-plugin-dialog needs but never a DPI declaration, so this app's own copy of that file adds one
    // alongside it rather than losing Common Controls by replacing the manifest outright.
    let windows = tauri_build::WindowsAttributes::new().app_manifest(include_str!("windows-app-manifest.xml"));
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(manifest)
            .windows_attributes(windows),
    )
    .expect("tauri build step");
}
