//! Check the compiled desktop artifact, not a feature value assembled by a unit test.

use std::fs;

const COMPILED_APP: &str = env!("CARGO_BIN_EXE_clotr");
const ONE_CLOTR_PERMISSION: &[u8] = b"allow-one-clotr-status";
const NATIVE_HOST_REGISTRATION: &[u8] = b"NativeMessagingHosts";

fn contains(bytes: &[u8], needle: &[u8]) -> bool {
    bytes.windows(needle.len()).any(|window| window == needle)
}

#[test]
fn compiled_app_has_one_clotr_capability_and_native_host_registration_only_when_enabled() {
    let app = fs::read(COMPILED_APP).expect("Cargo built the app artifact for this integration test");
    assert_eq!(
        contains(&app, ONE_CLOTR_PERMISSION),
        cfg!(feature = "one-clotr"),
        "the compiled capability permissions must match the commands registered in this build",
    );
    assert_eq!(
        contains(&app, NATIVE_HOST_REGISTRATION),
        cfg!(feature = "one-clotr"),
        "the native messaging host registry code must be absent when One Clotr is off",
    );
}

#[test]
fn generated_permissions_match_the_one_clotr_build_switch() {
    let root = std::path::PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let generated = root.join("permissions").join("autogenerated");
    assert!(generated.is_dir(), "tauri-build generated its command permissions");
    let mut permission_text = String::new();
    let files = walk(&generated);
    assert!(!files.is_empty(), "Tauri generated command permission files");
    for entry in files {
        if entry.extension().is_some_and(|extension| extension == "toml") {
            permission_text.push_str(&fs::read_to_string(entry).expect("read generated Tauri permissions"));
        }
    }
    let one_clotr_permissions = [
        "allow-one-clotr-status",
        "allow-one-clotr-consent",
        "allow-one-clotr-disconnect",
    ];
    let found: Vec<_> = one_clotr_permissions
        .iter()
        .map(|permission| permission_text.contains(permission))
        .collect();
    let expected = [cfg!(feature = "one-clotr"); 3];
    assert_eq!(
        found,
        expected,
        "the generated command permissions must be rebuilt for this Cargo feature set",
    );
}

fn walk(dir: &std::path::Path) -> Vec<std::path::PathBuf> {
    let mut files = Vec::new();
    for entry in fs::read_dir(dir).expect("read Tauri's generated permission directory") {
        let path = entry.expect("read generated permission entry").path();
        if path.is_dir() {
            files.extend(walk(&path));
        } else {
            files.push(path);
        }
    }
    files
}
